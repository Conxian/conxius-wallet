/**
 * Conformance against the official BIP-327 (MuSig2) test vectors for key
 * aggregation, key sorting, nonce aggregation, and partial-signature
 * aggregation. These cover the full `KeyAgg` + `ApplyTweak` + `GetSessionValues`
 * core that `signPartial` and `partialSigVerify` also share.
