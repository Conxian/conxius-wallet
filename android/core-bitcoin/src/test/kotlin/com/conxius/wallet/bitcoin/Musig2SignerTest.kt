class Musig2SignerTest {
    // ── KeyAgg vectors (bip-0327/vectors/key_agg_vectors.json) ──────────────
    private val aggPubkeys = listOf(
        "02F9308A019258C31049344F85F89D5229B531C845836F99B08601F113BCE036F9",
        "03DFF1D77F2A671C5F36183726DB2341BE58FEAE1DA2DECED843240F7B502BA659",
        "023590A94E768F8E1815C2F24B4D80A8E3149316C3518CE7B7AD338368D038CA66",
    )

    @Test
    fun keyAggVector0() = assertKeyAgg(listOf(0, 1, 2), "90539EEDE565F5D054F32CC0C220126889ED1E5D193BAF15AEF344FE59D4610C")

    @Test
    fun keyAggVector1() = assertKeyAgg(listOf(2, 1, 0), "6204DE8B083426DC6EAF9502D27024D53FC826BF7D2012148A0575435DF54B2B")

    @Test
    fun keyAggVector2() = assertKeyAgg(listOf(0, 0, 0), "B436E3BAD62B8CD409969A224731C193D051162D8C5AE8B109306127DA3AA935")

    @Test
    fun keyAggVector3() = assertKeyAgg(listOf(0, 0, 1, 1), "69BC22BFA5D106306E48A20679DE1D7389386124D07571D0D872686028C26A3E")

    private fun assertKeyAgg(indices: List<Int>, expected: String) {
        val keys = indices.map { Hex.decode(aggPubkeys[it]) }
        assertEquals(expected, Hex.toHexString(Musig2Signer.keyAggregate(keys)).uppercase())
    }

    // ── KeySort vectors (bip-0327/vectors/key_sort_vectors.json) ────────────
    @Test
    fun keySortVectors() {
        val input = listOf(
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EB8",
            "02F9308A019258C31049344F85F89D5229B531C845836F99B08601F113BCE036F9",
            "03DFF1D77F2A671C5F36183726DB2341BE58FEAE1DA2DECED843240F7B502BA659",
            "023590A94E768F8E1815C2F24B4D80A8E3149316C3518CE7B7AD338368D038CA66",
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EFF",
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EB8",
        )
        val expected = listOf(
            "023590A94E768F8E1815C2F24B4D80A8E3149316C3518CE7B7AD338368D038CA66",
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EB8",
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EB8",
            "02DD308AFEC5777E13121FA72B9CC1B7CC0139715309B086C960E18FD969774EFF",
            "02F9308A019258C31049344F85F89D5229B531C845836F99B08601F113BCE036F9",
            "03DFF1D77F2A671C5F36183726DB2341BE58FEAE1DA2DECED843240F7B502BA659",
        )
        val sorted = Musig2Signer.keySort(input.map { Hex.decode(it) })
        assertEquals(expected, sorted.map { Hex.toHexString(it).uppercase() })
    }

